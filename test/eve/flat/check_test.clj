(ns eve.flat.check-test
  "Lane C4 — bytes nobody vouches for (IMPL-PLAN.md §3.3, C4.1–C4.4).
   The checker is eve.flat.check; the malformed corpus is
   test/eve/fixtures/flat-malformed.edn, generated by
   eve.flat.gen-fixtures from the valid chunks in eve.flat.chunk-gen."
  (:require [clojure.test :refer [deftest is testing]]
            [clojure.edn :as edn]
            [clojure.java.io :as io]
            [eve.flat.check :as check]
            [eve.flat.chunk-gen :as g])
  (:import #_{:clj-kondo/ignore [:unused-import]} ; Arrays is used below; the bare class name sits in the config's host-class unresolved-symbol exclusion (for the seats that reach it without an import), which blinds kondo to the import's use [java.util Arrays Random]))

(def fixture-path "test/eve/fixtures/flat-malformed.edn")

(defn- fixture-rows []
  (edn/read-string (slurp (io/file fixture-path))))

(defn- refusal-check
  "The :check name when bs is refused, ::accepted when it is not,
   ::host-error when anything but a typed refusal escapes."
  [bs]
  (try
    (check/open-checked bs)
    ::accepted
    (catch clojure.lang.ExceptionInfo e
      (let [c (:check (ex-data e))]
        (if c c ::host-error)))
    (catch Throwable _ ::host-error)))

;; ------------------------------------------------------------------ sanity

(deftest valid-chunks-are-accepted
  (testing "the checker does not refuse the chunks the corpus is built from"
    (doseq [[name bs] (g/valid-chunks)]
      (is (check/checked? (check/open-checked bs)) (str "valid chunk " name))
      (is (Arrays/equals bs (check/checked-bytes (check/open-checked bs)))
          (str "handle carries the bytes of " name)))))

;; ------------------------------------------------------------------ C4.1

(deftest malformed-refused-by-name
  (let [rows (fixture-rows)]
    (is (seq rows) "the malformed corpus is not empty")
    (doseq [{:keys [note check bytes]} rows]
      (is (= check (refusal-check (g/hex->bytes bytes)))
          (str "fixture: " note)))))

;; ------------------------------------------------------------------ C4.2

(defn- nested-vec-chunk
  "A chunk of depth nested VECs around one scalar."
  [depth]
  (g/packed-chunk
   {:syms [] :shapes []
    :emit (fn [b]
            (loop [i 0 prev (g/emit-scalar b 1)]
              (if (< i depth)
                (recur (inc i) (g/emit-vec b false [prev]))
                prev)))}))

(deftest limits-enforced
  (testing "10,000 levels of nesting are refused by name, not by stack"
    (is (= :nesting-too-deep (refusal-check (nested-vec-chunk 10000)))))
  (testing "the depth limit is a boundary: at it passes, past it refuses"
    (is (= ::accepted (refusal-check (nested-vec-chunk 64))))
    (is (= :nesting-too-deep (refusal-check (nested-vec-chunk 65)))))
  (testing "a lying count is refused before any element is read"
    (let [bs (g/packed-chunk
              {:syms [] :shapes []
               :emit (fn [b] (let [s (g/emit-scalar b 1) o (g/pos b)]
                               (g/w8 b 0x22) (g/wvarint b 4294967295) (g/woff b false s) o))})]
      (is (= :count-exceeds-bytes (refusal-check bs))))
    (let [bs (g/packed-chunk
              {:syms [] :shapes []
               :emit (fn [b] (let [o (g/pos b)]
                               (g/w8 b 0x23) (g/wvarint b 10000000)
                               (g/wbytes b (g/col-bytes 6 (g/dense-data 4 [1])))
                               o))})]
      (is (= :count-exceeds-bytes (refusal-check bs))))))

