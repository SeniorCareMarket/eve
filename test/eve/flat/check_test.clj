(defn- mutate [^Random rng ^bytes bs]
  (let [n (alength bs)
        op (.nextInt rng 4)]
    (case op
      0 (if (zero? n) bs (g/set-byte bs (.nextInt rng n) (.nextInt rng 256)))
      1 (if (zero? n) bs (let [i (.nextInt rng n)]
                           (g/set-byte bs i (bit-xor (g/u8-at bs i) (bit-shift-left 1 (.nextInt rng 8))))))
      2 (g/truncate bs (.nextInt rng (inc n)))
      3 (g/append-bytes bs (repeatedly (inc (.nextInt rng 8)) #(.nextInt rng 256))))))

(deftest fuzz-never-crashes
  (let [rng (Random. 20261112)
        sources (vec (vals (g/valid-chunks)))
        mutants (for [src sources
                      _ (range 250)]
                  (mutate rng src))
        escapes (transient [])]
    (doseq [m mutants]
      (try
        (check/open-checked m)
        (catch clojure.lang.ExceptionInfo e
          (when-not (:check (ex-data e))
            (conj! escapes {:bytes (g/bytes->hex m) :escape (str e)})))
        (catch Throwable t
          (conj! escapes {:bytes (g/bytes->hex m)
                          :escape (str (class t) ": " (.getMessage t))}))))
    (let [es (persistent! escapes)]
      (is (empty? es)
          (str "fuzz escapes (want none): " (pr-str (take 3 es)))))))

;; ------------------------------------------------------------------ C4.4

(deftest place-requires-checked
  (let [valid (:vec (g/valid-chunks))
        h (check/open-checked valid)]
    (testing "a checked handle is accepted and yields exactly its bytes"
      (is (check/checked? h))
      (is (Arrays/equals valid (check/require-checked h))))
    (testing "raw bytes, however valid, are not a checked handle"
      (is (not (check/checked? valid)))
      (is (= :unchecked-bytes
             (try (check/require-checked valid)
                  (catch clojure.lang.ExceptionInfo e (:check (ex-data e)))))))
    (testing "anything else is refused the same way"
      (doseq [x [nil "EVS1" [] 42]]
        (is (= :unchecked-bytes
               (try (check/require-checked x)
                    (catch clojure.lang.ExceptionInfo e (:check (ex-data e)))))
            (str "input: " (pr-str x)))))))
